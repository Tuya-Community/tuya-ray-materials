/**
 * 根据图片名称获取主题适配的 CSS 类名
 * @param imageName 图片名称（res 对象中的 key）
 * @returns CSS 类名，如果未配置则返回空字符串（表示彩色图片，不做改变）
 */
export const getImageThemeClass = (imageName: string): string => {
  const themeType = IMAGE_THEME_TYPES[imageName];
  if (themeType === 'bw') {
    return 'img-theme-bw';
  }
  if (themeType === 'gray') {
    return 'img-theme-gray';
  }
  // 'color' 或未配置，返回空字符串，不做改变
  return '';
};

export default {
  ...res,
  getImageThemeClass,
  IMAGE_THEME_TYPES,
};
